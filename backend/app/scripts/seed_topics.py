async def seed_topics_and_recipients(session: AsyncSession):
    recipient_models = {}
    for r_data in RECIPIENTS_DATA:
        recip = TicketRecipient(
            code=r_data["code"],
            short_name=r_data["short_name"],
            full_name=r_data["full_name"],
            category=r_data["category"],
            icon=r_data["icon"],
        )
        session.add(recip)
        recipient_models[r_data["code"]] = recip

    await session.flush()

    for sec_num, sec_title, code, title, keywords in TOPICS_RAW:
        topic = TicketTopic(
            code=code,
            section_num=sec_num,
            section_title=sec_title,
            title=title,
            keywords=keywords,
        )

        codes = TOPIC_TO_RECIPIENTS.get(code, ["1"])
        for c in codes:
            if c in recipient_models:
                topic.recipients.append(recipient_models[c])

        session.add(topic)

    await session.flush()